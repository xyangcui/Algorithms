#!/usr/bin/env python3
"""
Generate ensemble INITIAL CONDITIONS only.

For each case:
    EDA mean = mean of the perturbed EDA members (control excluded)
    d_i      = EDA_i - EDA_mean
    p_i      = d_i + SV_i

The generated ensemble is:
    member 0       = control
    members 1..M   = control + p_i
    members M+1..2M= control - p_i

Total size = 1 + 2*M.

No forecast integration is performed.
"""

import json
import pickle
from pathlib import Path

import numpy as np


# ------------------------------------------------------------
# Configuration
# ------------------------------------------------------------
with open("config.json", "r") as f:
    config = json.load(f)

nx = config["model"]["nx"]
ny = config["model"]["ny"]
nfcst = config["forecast_evaluation"]["n_cases"]
eda_members = config["eda"]["default_members"]

EDA_FILE = Path("./eda_members/eda.pkl")
SV_DIR = Path("./sv_members")
OUT_DIR = Path(".")
OUT_DIR.mkdir(parents=True, exist_ok=True)



# ------------------------------------------------------------
# Load EDA states
#
# From SV.py:
# da.shape = (nfcst, 1 + eda_members, nx, ny)
#
# da[:, 0]   : control
# da[:, 1:]  : perturbed EDA members
# ------------------------------------------------------------
with open(EDA_FILE, "rb") as f:
    da = np.asarray(pickle.load(f))

expected_shape = (nfcst, 1 + eda_members, nx, ny)
if da.shape != expected_shape:
    raise ValueError(
        f"Expected EDA shape {expected_shape}, but got {da.shape}"
    )


# Store every case in one merged array:
# axis 0 = forecast case
# axis 1 = [control, positive members, negative members]
nens = 1 + 2 * eda_members
forecast_ensemble = np.empty(
    (nfcst, nens, nx, ny),
    dtype=da.dtype,
)


# ------------------------------------------------------------
# Generate initial-condition ensemble
# ------------------------------------------------------------
for icase in range(nfcst):

    case_no = icase + 1

    # Unperturbed control analysis
    control = da[icase, 0]

    # Perturbed EDA analyses only
    eda = da[icase, 1:]

    # ECMWF EDA perturbation definition:
    #
    #     d_i = EDA_i - mean(EDA)
    #
    # The control is NOT included in this EDA mean.
    eda_mean = np.mean(eda, axis=0)
    eda_pert = eda - eda_mean[None, :, :]

    # Singular vectors generated by SV.py:
    # shape = (eda_members, nx, ny)
    sv_file = SV_DIR / f"sv_{case_no:03d}.pkl"

    with open(sv_file, "rb") as f:
        sv = np.asarray(pickle.load(f))

    expected_sv_shape = (eda_members, nx, ny)
    if sv.shape != expected_sv_shape:
        raise ValueError(
            f"{sv_file}: expected {expected_sv_shape}, got {sv.shape}"
        )

    # --------------------------------------------------------
    # Combine EDA and SV perturbations
    #
    # p_i = (EDA_i - EDA_mean) + SV_i
    # --------------------------------------------------------
    perturb = eda_pert + sv

    # --------------------------------------------------------
    # 1 + 2*M ensemble:
    #
    # control
    # control + EDA_pert_i + SV_i
    # control - EDA_pert_i - SV_i
    # --------------------------------------------------------
    nens = 1 + 2 * eda_members

    ensemble = np.empty(
        (nens, nx, ny),
        dtype=np.result_type(control, perturb),
    )

    ensemble[0] = control
    ensemble[1:1 + eda_members] = control[None, :, :] + perturb
    ensemble[1 + eda_members:] = control[None, :, :] - perturb

    # Put this case into the merged ensemble array.
    forecast_ensemble[icase] = ensemble

    print(
        f"case {case_no:03d}: generated, "
        f"case shape={ensemble.shape}"
    )


# ------------------------------------------------------------
# Store all forecast cases in ONE array/file
#
# shape:
#   (nfcst, 1 + 2*eda_members, nx, ny)
# ------------------------------------------------------------
outfile = OUT_DIR / "forecast_ensemble.pkl"

with open(outfile, "wb") as f:
    pickle.dump(forecast_ensemble, f, protocol=pickle.HIGHEST_PROTOCOL)

print(f"saved merged ensemble: {outfile}")
print(f"forecast_ensemble.shape = {forecast_ensemble.shape}")
